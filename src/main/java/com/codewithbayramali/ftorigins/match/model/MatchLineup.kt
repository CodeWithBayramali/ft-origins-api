package com.codewithbayramali.ftorigins.match.model

import com.codewithbayramali.ftorigins.geo.model.Region
import com.codewithbayramali.ftorigins.model.BaseEntity
import jakarta.persistence.Column
import jakarta.persistence.Entity
import jakarta.persistence.EnumType
import jakarta.persistence.Enumerated
import jakarta.persistence.FetchType
import jakarta.persistence.JoinColumn
import jakarta.persistence.ManyToOne
import jakarta.persistence.Table
import jakarta.persistence.UniqueConstraint
import java.util.UUID

/**
 * One side's lineup choice for a match (the picked players live in MatchParticipant rows).
 * Founder-submitted, or system-built at kickoff when no founder acted ([autoGenerated]).
 */
@Entity
@Table(
    name = "match_lineups",
    uniqueConstraints = [UniqueConstraint(name = "uq_match_lineups", columnNames = ["match_id", "region_id"])]
)
class MatchLineup : BaseEntity() {

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "match_id", nullable = false)
    var match: Match? = null

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "region_id", nullable = false)
    var region: Region? = null

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 8)
    var formation: Formation = Formation.F_2_2_1

    /** Audit only (the founder at submit time); plain id — never traversed. */
    @Column(name = "submitted_by_player_id")
    var submittedByPlayerId: UUID? = null

    @Column(name = "auto_generated", nullable = false)
    var autoGenerated: Boolean = true
}
