package com.codewithbayramali.ftorigins.match.dto

import com.codewithbayramali.ftorigins.match.model.Formation
import com.codewithbayramali.ftorigins.match.model.MatchRole
import java.time.Instant
import java.util.UUID

// (FormationOptionResponse below exposes the Formation enum to clients as data.)

/** One lineup slot. [overall] is the member's current effective overall (null for an AI filler). */
data class LineupSlotResponse(
    val slot: Int,
    val role: MatchRole,
    val playerId: UUID?,
    val displayName: String?,
    val kitNumber: Int?,
    val overall: Int?,
    val aiFill: Boolean
)

/** A formation the founder can pick, with its slot->role layout so the client never hardcodes it. */
data class FormationOptionResponse(
    val name: String,
    /** Human label derived from the shape, e.g. "2-2-1" (the GK is implicit). */
    val label: String,
    val roles: List<MatchRole>
) {
    companion object {
        @JvmStatic
        fun all(): List<FormationOptionResponse> = Formation.entries.map { formation ->
            val outfield = formation.roles.drop(1)
            FormationOptionResponse(
                name = formation.name,
                label = listOf(MatchRole.DEF, MatchRole.MID, MatchRole.FWD)
                    .joinToString("-") { role -> outfield.count { it == role }.toString() },
                roles = formation.roles
            )
        }
    }
}

/**
 * One side's lineup as the managing client sees it. When no lineup was submitted yet, [slots] is a
 * live SUGGESTION (best members by role, [autoGenerated] = true) that is not persisted until the
 * founder saves it. [canEdit] = caller is the founder and [locked] is false.
 */
data class LineupResponse(
    val matchId: UUID,
    val regionId: UUID,
    val formation: Formation,
    val autoGenerated: Boolean,
    /** True once edits are closed: lock time passed, or the match already left SCHEDULED. */
    val locked: Boolean,
    /** When lineup edits close (kickoff minus the configured lock window). */
    val locksAt: Instant,
    val canEdit: Boolean,
    val slots: List<LineupSlotResponse>,
    /** Every formation the founder may choose, with its slot layout. */
    val availableFormations: List<FormationOptionResponse> = FormationOptionResponse.all(),
    // Live-match management. While a match runs the lineup can't be re-picked, but the founder may
    // still substitute — a different permission with its own budget.
    val live: Boolean = false,
    val substitutionsUsed: Int = 0,
    val substitutionsAllowed: Int = 0,
    /** Caller is the founder, the match is live and there are substitutions left. */
    val canSubstitute: Boolean = false,
    /** Live match clock (0 before kickoff). */
    val simMinute: Int = 0
)
