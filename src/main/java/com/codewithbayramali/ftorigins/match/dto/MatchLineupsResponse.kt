package com.codewithbayramali.ftorigins.match.dto

import com.codewithbayramali.ftorigins.match.model.Formation
import com.codewithbayramali.ftorigins.match.model.MatchRole
import com.codewithbayramali.ftorigins.player.model.PlayerAppearance
import java.util.UUID

/**
 * One participant as the spectator client renders it. [enteredMinute]/[leftMinute] bound the slot
 * occupancy window — "who is slot 3 at minute 70" resolves through these. [appearance] and
 * [bootDesignId] dress the avatar; both are null for AI fillers (client uses its defaults).
 *
 * [pace] is the kickoff snapshot of the player's effective pace, and it is here for one reason: how
 * fast a body runs on the broadcast must be the SERVER's answer, not the client's. Without it every
 * player on the pitch moved at the same invented speed and a 90-pace winger looked exactly like a
 * 35-pace filler. Null before kickoff (no snapshot yet) — the client falls back to a standard pace.
 */
data class MatchParticipantResponse(
    val slot: Int,
    val role: MatchRole,
    val playerId: UUID?,
    val displayName: String?,
    val kitNumber: Int?,
    val aiFill: Boolean,
    val enteredMinute: Int,
    val leftMinute: Int?,
    val overall: Int?,
    val pace: Int?,
    val appearance: PlayerAppearance?,
    val bootDesignId: Int?
)

/** [formation]/[autoGenerated] are null while a side hasn't been finalized yet (pre-kickoff). */
data class MatchSideLineupResponse(
    val regionId: UUID,
    val formation: Formation?,
    val autoGenerated: Boolean?,
    val participants: List<MatchParticipantResponse>
)

/** Both sides' lineups — the spectator/visualizer view (management editing stays on /lineup). */
data class MatchLineupsResponse(
    val matchId: UUID,
    val home: MatchSideLineupResponse,
    val away: MatchSideLineupResponse
)
