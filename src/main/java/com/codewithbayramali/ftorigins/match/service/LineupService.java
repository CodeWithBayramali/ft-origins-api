package com.codewithbayramali.ftorigins.match.service;

import com.codewithbayramali.ftorigins.exception.BusinessException;
import com.codewithbayramali.ftorigins.exception.NotFoundException;
import com.codewithbayramali.ftorigins.geo.model.Region;
import com.codewithbayramali.ftorigins.match.dto.FormationOptionResponse;
import com.codewithbayramali.ftorigins.match.dto.LineupRequest;
import com.codewithbayramali.ftorigins.match.dto.LineupResponse;
import com.codewithbayramali.ftorigins.match.dto.LineupSlotResponse;
import com.codewithbayramali.ftorigins.match.model.Formation;
import com.codewithbayramali.ftorigins.match.model.Match;
import com.codewithbayramali.ftorigins.match.model.MatchLineup;
import com.codewithbayramali.ftorigins.match.model.MatchParticipant;
import com.codewithbayramali.ftorigins.match.model.MatchStatus;
import com.codewithbayramali.ftorigins.match.repository.MatchCommandRepository;
import com.codewithbayramali.ftorigins.match.repository.MatchLineupRepository;
import com.codewithbayramali.ftorigins.match.repository.MatchParticipantRepository;
import com.codewithbayramali.ftorigins.match.repository.MatchRepository;
import com.codewithbayramali.ftorigins.player.model.Player;
import com.codewithbayramali.ftorigins.player.repository.PlayerRepository;
import com.codewithbayramali.ftorigins.player.service.EffectiveAttributes;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.UUID;
import java.util.function.Function;
import java.util.stream.Collectors;

/**
 * The founder's lineup management for a single match side. Reading returns the submitted lineup,
 * or a non-persisted best-members suggestion when nothing was submitted yet; writing is
 * founder-only and closes at the lock time (kickoff minus the configured window) — from then on
 * the kickoff job owns the lineup (snapshotting stats, AI-filling empty slots).
 */
@Service
public class LineupService {

    private final MatchRepository matchRepository;
    private final MatchLineupRepository lineupRepository;
    private final MatchParticipantRepository participantRepository;
    private final MatchCommandRepository commandRepository;
    private final PlayerRepository playerRepository;
    private final FounderGuard founderGuard;
    private final DefaultLineupFactory defaultLineupFactory;
    private final Duration lineupLock;
    private final int maxSubstitutions;

    public LineupService(MatchRepository matchRepository,
                         MatchLineupRepository lineupRepository,
                         MatchParticipantRepository participantRepository,
                         MatchCommandRepository commandRepository,
                         PlayerRepository playerRepository,
                         FounderGuard founderGuard,
                         DefaultLineupFactory defaultLineupFactory,
                         @Value("${app.match.lineup-lock-minutes:15}") long lineupLockMinutes,
                         @Value("${app.match.max-substitutions:3}") int maxSubstitutions) {
        this.matchRepository = matchRepository;
        this.lineupRepository = lineupRepository;
        this.participantRepository = participantRepository;
        this.commandRepository = commandRepository;
        this.playerRepository = playerRepository;
        this.founderGuard = founderGuard;
        this.defaultLineupFactory = defaultLineupFactory;
        this.lineupLock = Duration.ofMinutes(lineupLockMinutes);
        this.maxSubstitutions = maxSubstitutions;
    }

    /** The caller's side of the match: submitted lineup, or a live suggestion when none exists yet. */
    @Transactional(readOnly = true)
    public LineupResponse getMyLineup(UUID userId, UUID matchId) {
        Match match = loadMatch(matchId);
        Player caller = loadPlayer(userId);
        Region side = resolveSide(match, caller);

        return lineupRepository.findByMatchIdAndRegionId(matchId, side.getId())
                .map(lineup -> toResponse(match, side, caller, lineup.getFormation(), lineup.getAutoGenerated(),
                        fromParticipants(participantRepository
                                .findByMatchIdAndRegionIdAndLeftMinuteIsNullOrderBySlot(matchId, side.getId()))))
                .orElseGet(() -> toResponse(match, side, caller, DefaultLineupFactory.DEFAULT_FORMATION, true,
                        suggestSlots(side)));
    }

    /** Founder-only submit; replaces the side's previous choice wholesale. */
    @Transactional
    public LineupResponse submit(UUID userId, UUID matchId, LineupRequest request) {
        Match match = loadMatch(matchId);
        Player caller = loadPlayer(userId);
        Region side = resolveSide(match, caller);
        founderGuard.requireFounder(caller, side);
        requireEditable(match);

        Formation formation = request.getFormation();
        List<UUID> starterIds = request.getStarterPlayerIds();
        Map<UUID, Player> members = playerRepository.findByRegionId(side.getId()).stream()
                .collect(Collectors.toMap(Player::getId, Function.identity()));
        List<Player> starters = resolveStarters(starterIds, members);

        MatchLineup lineup = lineupRepository.findByMatchIdAndRegionId(matchId, side.getId())
                .orElseGet(MatchLineup::new);
        lineup.setMatch(match);
        lineup.setRegion(side);
        lineup.setFormation(formation);
        lineup.setSubmittedByPlayerId(caller.getId());
        lineup.setAutoGenerated(false);
        lineupRepository.save(lineup);

        participantRepository.deleteForSide(matchId, side.getId());
        List<MatchParticipant> participants = new ArrayList<>(starters.size());
        for (int slot = 0; slot < starters.size(); slot++) {
            participants.add(buildParticipant(match, side, formation, slot, starters.get(slot)));
        }
        participantRepository.saveAll(participants);

        return toResponse(match, side, caller, formation, false, fromParticipants(participants));
    }

    // -- loading & authorization -------------------------------------------------

    private Match loadMatch(UUID matchId) {
        return matchRepository.findDetailById(matchId)
                .orElseThrow(() -> new NotFoundException("MATCH_NOT_FOUND", "Match not found"));
    }

    private Player loadPlayer(UUID userId) {
        return playerRepository.findDetailByUserId(userId)
                .orElseThrow(() -> new NotFoundException("PLAYER_NOT_FOUND", "No player profile for this account"));
    }

    /** The caller's team must actually play this match; spectators use the match/timeline endpoints. */
    private Region resolveSide(Match match, Player caller) {
        UUID regionId = caller.getRegion().getId();
        if (regionId.equals(match.getHomeRegion().getId())) {
            return match.getHomeRegion();
        }
        if (regionId.equals(match.getAwayRegion().getId())) {
            return match.getAwayRegion();
        }
        throw new BusinessException(HttpStatus.FORBIDDEN, "NOT_IN_MATCH", "Your team is not part of this match");
    }

    private void requireEditable(Match match) {
        if (match.getStatus() != MatchStatus.SCHEDULED || !Instant.now().isBefore(locksAt(match))) {
            throw new BusinessException(HttpStatus.CONFLICT, "LINEUP_LOCKED",
                    "Lineup changes are closed for this match");
        }
    }

    private Instant locksAt(Match match) {
        return match.getKickoffAt().minus(lineupLock);
    }

    // -- validation ----------------------------------------------------------------

    /**
     * Maps the slot-ordered id list to players (null = AI slot). Rejects ids from outside the team
     * and the same player in two slots.
     */
    private List<Player> resolveStarters(List<UUID> starterIds, Map<UUID, Player> members) {
        List<Player> starters = new ArrayList<>(starterIds.size());
        Set<UUID> seen = new HashSet<>();
        for (UUID id : starterIds) {
            if (id == null) {
                starters.add(null);
                continue;
            }
            Player member = members.get(id);
            if (member == null) {
                throw new BusinessException(HttpStatus.BAD_REQUEST, "NOT_A_MEMBER",
                        "Player " + id + " is not a member of this team");
            }
            if (!seen.add(id)) {
                throw new BusinessException(HttpStatus.BAD_REQUEST, "DUPLICATE_STARTER",
                        "The same player can't fill two lineup slots");
            }
            starters.add(member);
        }
        return starters;
    }

    // -- assembly --------------------------------------------------------------------

    private MatchParticipant buildParticipant(Match match, Region side, Formation formation,
                                              int slot, Player player) {
        MatchParticipant participant = new MatchParticipant();
        participant.setMatch(match);
        participant.setRegion(side);
        participant.setSlot(slot);
        participant.setRole(formation.getRoles().get(slot));
        participant.setPlayer(player);
        participant.setAiFill(player == null);
        if (player != null) {
            // Display convenience for pre-kickoff views; the kickoff job re-snapshots these
            // together with the stats (and names the AI fillers).
            participant.setDisplayName(player.getDisplayName());
            participant.setKitNumber(player.getAppearance().getKitNumber());
            participant.setPreferredFoot(player.getPreferredFoot());
        }
        return participant;
    }

    private List<LineupSlotResponse> fromParticipants(List<MatchParticipant> participants) {
        return participants.stream()
                .map(p -> new LineupSlotResponse(
                        p.getSlot(),
                        p.getRole(),
                        p.getPlayer() != null ? p.getPlayer().getId() : null,
                        p.getDisplayName(),
                        p.getKitNumber(),
                        p.getPlayer() != null ? EffectiveAttributes.of(p.getPlayer()).overall() : null,
                        p.getAiFill()))
                .toList();
    }

    private List<LineupSlotResponse> suggestSlots(Region side) {
        List<Player> members = playerRepository.findByRegionId(side.getId());
        return defaultLineupFactory.build(DefaultLineupFactory.DEFAULT_FORMATION, members).stream()
                .map(s -> new LineupSlotResponse(
                        s.slot(),
                        s.role(),
                        s.player() != null ? s.player().getId() : null,
                        s.player() != null ? s.player().getDisplayName() : null,
                        s.player() != null ? s.player().getAppearance().getKitNumber() : null,
                        s.player() != null ? EffectiveAttributes.of(s.player()).overall() : null,
                        s.player() == null))
                .toList();
    }

    private LineupResponse toResponse(Match match, Region side, Player caller,
                                      Formation formation, boolean autoGenerated,
                                      List<LineupSlotResponse> slots) {
        Instant locksAt = locksAt(match);
        boolean locked = match.getStatus() != MatchStatus.SCHEDULED || !Instant.now().isBefore(locksAt);
        boolean isFounder = founderGuard.isFounder(caller, side);
        boolean canEdit = !locked && isFounder;

        // A live match can't be re-picked, but the founder may still substitute — separate right,
        // separate budget.
        boolean live = match.getStatus() == MatchStatus.LIVE;
        int used = live ? (int) commandRepository.countByMatchIdAndRegionId(match.getId(), side.getId()) : 0;
        boolean canSubstitute = live && isFounder && used < maxSubstitutions;

        return new LineupResponse(match.getId(), side.getId(), formation, autoGenerated,
                locked, locksAt, canEdit, slots, FormationOptionResponse.all(),
                live, used, maxSubstitutions, canSubstitute, match.getSimMinute());
    }
}
